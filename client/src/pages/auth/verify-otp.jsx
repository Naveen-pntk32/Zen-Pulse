import { useState } from "react";
import { Link, useLocation } from "wouter";
import { ShieldAlert, ArrowRight, RotateCcw } from "lucide-react";
import { AuthLayout } from "@/components/layout/AuthLayout";

export default function VerifyOTPPage() {
  const [, setLocation] = useLocation();
  const [digits, setDigits] = useState(["", "", "", "", "", ""]);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  const handleDigitChange = (index, value) => {
    if (!/^[0-9]?$/.test(value)) return;
    const next = [...digits];
    next[index] = value;
    setDigits(next);

    // Auto-focus next input
    if (value && index < 5) {
      const nextInput = document.getElementById(`otp-input-${index + 1}`);
      if (nextInput) nextInput.focus();
    }
  };

  const handleKeyDown = (index, e) => {
    if (e.key === "Backspace" && !digits[index] && index > 0) {
      const prevInput = document.getElementById(`otp-input-${index - 1}`);
      if (prevInput) prevInput.focus();
    }
  };

  const handleVerify = (e) => {
    e.preventDefault();
    const code = digits.join("");
    if (code.length !== 6) {
      setError("Please enter the complete 6-digit verification code.");
      return;
    }
    setError("");
    setLoading(true);
    setTimeout(() => {
      setLoading(false);
      setLocation("/pomodoro");
    }, 800);
  };

  return (
    <AuthLayout
      title="Two-Factor Authentication"
      subtitle="Enter the 6-digit security code generated by your authenticator app."
      backTo="/login"
    >
      <form onSubmit={handleVerify} className="space-y-6">
        {error && (
          <div className="p-3 rounded-[4px] border border-red-500/30 bg-red-500/10 text-xs text-red-400 font-mono">
            {error}
          </div>
        )}

        <div className="flex items-center justify-center gap-2 sm:gap-3">
          {digits.map((digit, idx) => (
            <input
              key={idx}
              id={`otp-input-${idx}`}
              type="text"
              inputMode="numeric"
              maxLength={1}
              autoFocus={idx === 0}
              value={digit}
              onChange={(e) => handleDigitChange(idx, e.target.value)}
              onKeyDown={(e) => handleKeyDown(idx, e)}
              className="w-10 h-12 sm:w-12 sm:h-14 text-center rounded-[6px] border border-border bg-surface text-lg font-mono font-bold text-foreground focus:border-greptile-green focus:outline-none focus:ring-1 focus:ring-greptile-green transition-all"
            />
          ))}
        </div>

        <button
          type="submit"
          disabled={loading}
          className="w-full py-3 rounded-[4px] bg-greptile-green hover:bg-[#34f5ab] text-black font-mono text-xs font-bold uppercase tracking-wider flex items-center justify-center gap-2 transition-all shadow-[0_0_20px_rgba(40,233,159,0.3)] disabled:opacity-50"
        >
          {loading ? "Verifying Token..." : (
            <>
              Verify Token <ArrowRight className="w-3.5 h-3.5" />
            </>
          )}
        </button>

        <div className="text-center pt-2 text-xs font-mono text-muted-foreground">
          Lost your device?{" "}
          <Link href="/support" className="text-greptile-green hover:underline">
            Use recovery key
          </Link>
        </div>
      </form>
    </AuthLayout>
  );
}
